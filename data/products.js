/** Products belonging to a named homepage collection, in catalogue order. */
export function getByCollection(collection) {
  return products.filter((product) => product.collections.includes(collection))
}

export function getProductBySlug(slug) {
  return products.find((product) => product.slug === slug) ?? null
}

export function getProductsByCategory(category) {
  return products.filter((product) => product.category === category)
}

/** Same category first, then same brand, excluding the product itself. */
export function getRelatedProducts(product, limit = 4) {
  if (!product) return []
  const sameCategory = products.filter((p) => p.id !== product.id && p.category === product.category)
  const sameBrand = products.filter(
    (p) => p.id !== product.id && p.brand === product.brand && p.category !== product.category,
  )
  return [...sameCategory, ...sameBrand].slice(0, limit)
}

export function getBestSellers(limit = 8) {
  return [...products].sort((a, b) => b.reviewCount - a.reviewCount).slice(0, limit)
}

export function getDiscounted(limit = 8) {
  return products.filter((p) => p.discount > 0).slice(0, limit)
}
