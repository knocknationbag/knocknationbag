/** Every product shares the same spec keys so the PDP table is never ragged. */
function specs({ dimensions, weight, capacity, material, hardware, laptop = '—', warranty = '3 years' }) {
  return [
    { label: 'Dimensions', value: dimensions },
    { label: 'Weight', value: weight },
    { label: 'Capacity', value: capacity },
    { label: 'Main material', value: material },
    { label: 'Hardware', value: hardware },
    { label: 'Laptop sleeve', value: laptop },
    { label: 'Warranty', value: warranty },
  ]
}

/** Gallery = the product shot followed by shared lifestyle context frames. */
function gallery(main) {
  return [main, ...LIFESTYLE]
}

